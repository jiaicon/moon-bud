/**
 * 助手面板上"替人开口"的两样东西：三句例句，和表单顶部那一条横幅。
 * 它们都是文案，而文案是这个功能最容易说谎的地方——例句把人带去一个还没做的功能，
 * 得到的第一次回应是"我没看懂"；横幅在半空时说"填好了"，人就不会去检查那一格。
 * 所以文案放这儿，由测试逐条钉着，而不是散在三个页面的模板里。
 */

/**
 * 例句。判据写在测试里：两种意图都要有（含"提醒"的是设提醒，不含的是记一笔）、
 * 不许长到在手机上折行、也不许是"问数据"那一句——本期助手只会往里写，不会往外读。
 */
export const ASK_EXAMPLES: readonly string[] = ['刚刚瓶喂 120 毫升', '半小时后提醒我给宝宝换尿布', '每天早 8 点提醒吃维D 400IU']

/**
 * 表单顶部那一句。`dropped` 是服务端说"这几栏我没能填上"的唯一来源，
 * 它非空时这句必须改口：一份被清空过半的草稿配上"已按你说的话填好"，
 * 人就不会去补那一栏，而育儿记录里少一栏的代价是重复喂一次。
 *
 * 不逐条念路径：`event.payload` 这种串是我和契约之间的事，给人看只会是一脸问号。
 */
export function askBannerCopy(dropped: readonly string[]): string {
  return dropped.length === 0
    ? '助手按你说的话填好了，不对的地方点一下改'
    : '有些字段没填上，在下面补一下'
}
